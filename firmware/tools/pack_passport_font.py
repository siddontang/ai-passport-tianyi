"""Bake the bundled OFL Noto Sans SC subset into a flash-only 16 px raster font.

Requires Pillow and fontTools; no font parser or glyph cache runs on the C3.
"""
import argparse
import hashlib
import io
from pathlib import Path

from fontTools.ttLib import TTFont
from PIL import ImageFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "boards/common/fonts/cjk_font.bin"
OUTPUT = ROOT / "apps/ai-passport-wifi/passport_font.c"


def generate():
    packed = SOURCE.read_bytes()
    assert packed[:8] == b"AGLKTTF1"
    ttf = packed[32:]
    mapping = TTFont(io.BytesIO(ttf)).getBestCmap()
    hanzi = {ord(bytes((lead, trail)).decode("gb2312"))
             for lead in range(0xB0, 0xF8) for trail in range(0xA1, 0xFF)
             if not (lead == 0xD7 and trail >= 0xFA)}
    assert len(hanzi) == 6763 and hanzi <= mapping.keys()
    points = list(range(32, 127)) + sorted(cp for cp in mapping if 176 <= cp <= 0xFFFF)
    font = ImageFont.truetype(io.BytesIO(ttf), 16)
    bitmap = bytearray()
    glyphs = [(0, 0, 0, 0, 0, 0)]
    for cp in points:
        char = chr(cp)
        mask, (left, top) = font.getmask2(char, mode="L", anchor="ls")
        width, height = mask.size
        pixels = list(mask)
        glyphs.append((len(bitmap), round(font.getlength(char) * 16), width, height, left, -top - height))
        for i in range(0, len(pixels), 2):
            high = (pixels[i] * 15 + 127) // 255
            low = (pixels[i + 1] * 15 + 127) // 255 if i + 1 < len(pixels) else 0
            bitmap.append(high * 16 + low)
    lines = ["// Generated by tools/pack_passport_font.py. Noto Sans SC, SIL OFL 1.1.",
             "// License: boards/common/fonts/OFL.txt",
             f"// Source SHA256: {hashlib.sha256(packed).hexdigest()}",
             '#include "raster_font.h"', "", "static const uint8_t bitmap[] = {"]
    lines += ["    " + ",".join(f"0x{b:02x}" for b in bitmap[i:i + 24]) + "," for i in range(0, len(bitmap), 24)]
    lines += ["};", "static const raster_glyph_t glyphs[] = {"]
    lines += ["    {" + ",".join(map(str, g)) + "}," for g in glyphs]
    sparse = [cp - 176 for cp in points[95:]]
    lines += ["};", "static const uint16_t sparse[] = {"]
    lines += ["    " + ",".join(map(str, sparse[i:i + 16])) + "," for i in range(0, len(sparse), 16)]
    lines += ["};", f"static const uint8_t no_kerning[{len(glyphs)}] = {{0}};",
              "static const int8_t kern_values[1] = {0};",
              "const raster_font_t passport_font_16 = {",
              "    bitmap, glyphs, sparse, no_kerning, no_kerning, kern_values,",
              f"    {len(sparse)}, {len(glyphs)}, 0, 20, 4", "};", ""]
    return "\n".join(lines), len(points), len(bitmap)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content, count, size = generate()
    if args.check:
        assert OUTPUT.read_text() == content, "Regenerate passport_font.c"
    else:
        OUTPUT.write_text(content)
    print(f"Passport font: {count} glyphs, {size} bitmap bytes, flash only")
