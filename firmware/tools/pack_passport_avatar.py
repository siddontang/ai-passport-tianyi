#!/usr/bin/env python3
"""Pack the pixel expression atlas as 64x64 flash-resident RGB565 sprites."""
import argparse
import hashlib
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "apps/ai-passport-wifi"
SOURCE = APP / "avatar/tianyi-pixel-expressions.png"
OUTPUT = APP / "passport_avatar_data.cc"
SIZE = 64


def packed_frames(source=SOURCE):
    atlas = Image.open(source).convert("RGB")
    if atlas.width != atlas.height or atlas.width % 2:
        raise ValueError("Expected a square 2x2 atlas with even dimensions")
    tile = atlas.width // 2
    frames = []
    for row in range(2):
        for column in range(2):
            frame = atlas.crop((column * tile, row * tile, (column + 1) * tile, (row + 1) * tile))
            frame = frame.resize((SIZE, SIZE), Image.Resampling.NEAREST)
            rgb565 = bytearray()
            for red, green, blue in frame.getdata():
                pixel = ((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)
                rgb565.extend((pixel >> 8, pixel & 255))
            frames.append(bytes(rgb565))
    return frames


def source_code():
    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    lines = ["// Generated by tools/pack_passport_avatar.py; do not edit.",
             f"// Atlas SHA-256: {digest}", '#include "passport_avatar.h"',
             "namespace passport_wifi::avatar {",
             "alignas(4) const uint8_t kPixels[kFrames][kWidth * kHeight * 2] = {"]
    for frame in packed_frames():
        lines.append("    {")
        for offset in range(0, len(frame), 24):
            lines.append("        " + ",".join(f"0x{byte:02x}" for byte in frame[offset:offset + 24]) + ",")
        lines.append("    },")
    lines.extend(("};", "}  // namespace passport_wifi::avatar", ""))
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = source_code()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise SystemExit("Avatar pixels are stale; run tools/pack_passport_avatar.py")
    else:
        OUTPUT.write_text(expected)
    print(f"Avatar RGB565: four {SIZE}x{SIZE} frames, {4 * SIZE * SIZE * 2:,} bytes in flash, no framebuffer")


if __name__ == "__main__":
    main()
